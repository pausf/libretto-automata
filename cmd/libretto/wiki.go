// The per-project specs wiki, generated and never hand-edited.
//
// The obvious build is a markdown parser; the extraction is line-shaped —
// prefixes, headings, bullets — so a scanner covers it and a parser would be a
// dependency bought to avoid twenty lines. What counts as a criterion is
// spec-drift's own definition, a bullet with a Proof: beneath it, because two
// tools with two definitions would disagree about what a capability promises.

// wikiMarker opens every generated file. It is how the tool recognises its own:
// a README whose first line is anything else was written by a person, and the
// oldest rule in this repository is that the tool never overwrites what it did
// not create.
const wikiMarker = "<!-- generated by libretto wiki; edit the specs, then run: libretto wiki -->"

// wikiDirOrder is spec-drift's discovery order, verbatim. First hit wins.
var wikiDirOrder = []string{".agents/specs", "specs", "openspec", "docs/specs", "spec"}

type wikiCapability struct {
	name      string
	changed   string // last-changed date from git; empty is absent, never an error
	subject   string // last commit subject from git; same contract as changed
	governs   string
	intro     []string // prose before the first heading; absent is absent
	criteria  []wikiCriterion
	decisions []string // first line of each Prior decisions bullet
	raw       string   // the whole file, for the mention scan
}

// wikiCriterion is a Proof:-backed bullet with its citation split out. The
// definitions mirrored here (and in isEARS/proofResolves below) are spec-drift's;
// the script stays the authority and the wiki is an advisory display of it.
type wikiCriterion struct {
	text      string
	proofFile string
	proofTest string
}

// wikiHTMLMarker opens the generated viewer, first line, before the doctype —
// modern parsers allow a comment there and the ownership check stays one read.
const wikiHTMLMarker = "<!-- generated by libretto wiki; edit the specs, then run: libretto wiki --html -->"

func wiki(w io.Writer, projectDir string, args []string) error {
	htmlMode, openMode := false, false
	for _, a := range args {
		switch a {
		case "--html":
			htmlMode = true
		case "--open":
			// Opening implies the view being opened — a browser does not render
			// the markdown side.
			htmlMode, openMode = true, true
		default:
			return fmt.Errorf("unknown argument %q — wiki takes only --html and --open", a)
		}
	}

	specsDir, found := findSpecsDir(projectDir)
	if !found {
		return fmt.Errorf("no specs directory found (looked for %s)", strings.Join(wikiDirOrder, ", "))
	}

	entries, err := os.ReadDir(specsDir) // sorted by name: determinism is structural
	if err != nil {
		return err
	}
	var caps []wikiCapability
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		specPath := filepath.Join(specsDir, e.Name(), "spec.md")
		b, err := os.ReadFile(specPath)
		if err != nil {
			continue // a directory without a spec.md is not a capability
		}
		c := parseSpec(strings.NewReader(string(b)), e.Name())
		c.raw = string(b)
		c.changed = wikiGitDate(projectDir, specPath)
		c.subject = wikiGitSubject(projectDir, specPath)
		caps = append(caps, c)
	}
	if len(caps) == 0 {
		return fmt.Errorf("%s holds no */spec.md — an empty specification has nothing to index", specsDir)
	}

	if htmlMode {
		htmlPath := filepath.Join(specsDir, "wiki.html")
		if err := writeMarked(htmlPath, wikiHTMLMarker, renderWikiHTML(projectDir, caps)); err != nil {
			return err
		}
		fmt.Fprintf(w, "wrote %s   (%d capabilities)\n", htmlPath, len(caps))
		if openMode {
			// Only after a successful write. A failed open leaves the file — the
			// error names it so the user can open it by hand.
			if err := openViewer(htmlPath); err != nil {
				return fmt.Errorf("wrote %s but could not open it: %w", htmlPath, err)
			}
			fmt.Fprintf(w, "opened %s\n", htmlPath)
		}
		return nil
	}

	readmePath := filepath.Join(specsDir, "README.md")
	if err := writeMarked(readmePath, wikiMarker, renderWiki(projectDir, caps)); err != nil {
		return err
	}
	fmt.Fprintf(w, "wrote %s   (%d capabilities)\n", readmePath, len(caps))

	// A marked wiki.html refreshes in the same run, so the one landing-step
	// invocation keeps every view this tool owns current. A foreign one is left
	// alone silently — erroring here would block every landing regeneration.
	htmlPath := filepath.Join(specsDir, "wiki.html")
	if ownsFile(htmlPath, wikiHTMLMarker) {
		if err := os.WriteFile(htmlPath, renderWikiHTML(projectDir, caps), 0o644); err != nil {
			return err
		}
		fmt.Fprintf(w, "refreshed %s\n", htmlPath)
	}
	return nil
}

// openerArgv is pure so the platform mapping is testable without executing it.
func openerArgv(goos, path string) []string {
	if goos == "darwin" {
		return []string{"open", path}
	}
	return []string{"xdg-open", path}
}

// openViewer hands a file to the platform's opener, detached — Start, not Run,
// so a misconfigured handler cannot block the panel mid-action. A var so tests
// observe the call instead of launching browsers.
var openViewer = func(path string) error {
	argv := openerArgv(runtime.GOOS, path)
	return exec.Command(argv[0], argv[1:]...).Start()
}

// findSpecsDir is the one discovery both the command and the panel's row share —
// a second list would disagree with this one exactly when it matters.
func findSpecsDir(projectDir string) (string, bool) {
	for _, candidate := range wikiDirOrder {
		if info, err := os.Stat(filepath.Join(projectDir, candidate)); err == nil && info.IsDir() {
			return filepath.Join(projectDir, candidate), true
		}
	}
	return "", false
}

// ownsFile reports whether path exists and opens with marker.
func ownsFile(path, marker string) bool {
	b, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	first, _, _ := strings.Cut(string(b), "\n")
	return first == marker
}

// writeMarked is the one implementation of "never overwrite what the tool did
// not create" for every generated view: an existing file whose first line is not
// the marker is somebody's, and it stays theirs.
func writeMarked(path, marker string, content []byte) error {
	if b, err := os.ReadFile(path); err == nil {
		first, _, _ := strings.Cut(string(b), "\n")
		if first != marker {
			return fmt.Errorf("%s exists and was not generated by libretto wiki — not touching it", path)
		}
	}
	return os.WriteFile(path, content, 0o644)
}

// parseSpec reads one capability spec in a single pass. The intro is the first
// run of prose lines before the first heading after the title; a criterion is a
// bullet block carrying a Proof: line, captured without it.
func parseSpec(r io.Reader, name string) wikiCapability {
	c := wikiCapability{name: name}
	var bullet []string
	proof, section := "", ""
	introDone, inBullet := false, false

	flush := func() {
		if inBullet && proof != "" && len(bullet) > 0 {
			cr := wikiCriterion{text: strings.Join(bullet, " ")}
			fields := strings.Fields(proof)
			if len(fields) > 0 {
				cr.proofFile = fields[0]
			}
			if len(fields) > 1 {
				cr.proofTest = fields[1]
			}
			c.criteria = append(c.criteria, cr)
		}
		bullet, proof, inBullet = nil, "", false
	}

	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for sc.Scan() {
		line := sc.Text()
		trimmed := strings.TrimSpace(line)

		switch {
		case strings.HasPrefix(trimmed, "- "):
			flush()
			inBullet = true
			bullet = append(bullet, strings.TrimPrefix(trimmed, "- "))
			if section == "Prior decisions" {
				c.decisions = append(c.decisions, strings.TrimPrefix(trimmed, "- "))
			}
			continue
		case inBullet && strings.HasPrefix(line, " ") && trimmed != "":
			if strings.HasPrefix(trimmed, "Proof:") {
				if proof == "" {
					proof = strings.TrimSpace(strings.TrimPrefix(trimmed, "Proof:"))
				}
			} else {
				bullet = append(bullet, trimmed)
			}
			continue
		}
		flush()

		switch {
		case strings.HasPrefix(trimmed, "#"):
			introDone = introDone || strings.HasPrefix(trimmed, "##")
			if strings.HasPrefix(trimmed, "## ") {
				section = strings.TrimSpace(strings.TrimPrefix(trimmed, "## "))
			}
		case strings.HasPrefix(trimmed, "Governs:"):
			if c.governs == "" {
				c.governs = strings.TrimSpace(strings.TrimPrefix(trimmed, "Governs:"))
			}
		case strings.HasPrefix(trimmed, "Targets:"), trimmed == "":
			// structural, never prose
		default:
			if !introDone {
				c.intro = append(c.intro, trimmed)
			}
		}
	}
	flush()
	return c
}

func renderWiki(projectDir string, caps []wikiCapability) []byte {
	var b strings.Builder
	b.WriteString(wikiMarker + "\n\n")
	fmt.Fprintf(&b, "# Specs — %s\n\n", filepath.Base(projectDir))
	b.WriteString("| Capability | Governs | What it promises |\n|---|---|---|\n")
	for _, c := range caps {
		fmt.Fprintf(&b, "| [%s](%s/spec.md) | `%s` | %s |\n",
			c.name, c.name, tableCell(c.governs), tableCell(firstSentence(c.intro)))
	}
	for _, c := range caps {
		fmt.Fprintf(&b, "\n## %s\n\n", c.name)
		if len(c.intro) > 0 {
			b.WriteString(strings.Join(c.intro, " ") + "\n\n")
		}
		if c.governs != "" {
			fmt.Fprintf(&b, "Governs: `%s`\n\n", c.governs)
		}
		for _, crit := range c.criteria {
			fmt.Fprintf(&b, "- %s\n", crit)
		}
		if len(c.criteria) > 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "[full spec](%s/spec.md)\n", c.name)
	}
	return []byte(b.String())
}

func firstSentence(intro []string) string {
	if len(intro) == 0 {
		return ""
	}
	joined := strings.Join(intro, " ")
	if cut := strings.Index(joined, ". "); cut >= 0 {
		return joined[:cut+1]
	}
	return joined
}

// tableCell keeps a pipe in spec prose from tearing the index table apart.
func tableCell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// Inline markup arrives from spec prose. Escaping runs first, always: the
// conversions below operate on escaped text, so no raw spec byte ever reaches
// markup position. That order is the whole of the escaping criterion.
var (
	wikiBoldRe = regexp.MustCompile(`\*\*([^*]+)\*\*`)
	wikiCodeRe = regexp.MustCompile("`([^`]+)`")
)

func htmlInline(s string) string {
	s = html.EscapeString(s)
	s = wikiBoldRe.ReplaceAllString(s, "<strong>$1</strong>")
	s = wikiCodeRe.ReplaceAllString(s, "<code>$1</code>")
	return s
}

// wikiGitDate answers "when did this spec last change" from the only clock
// that survives a clone: git history. Any failure — no git, no repository, no
// commits touching the file — is an empty string, and the date is simply
// absent from the page. A var so tests inject dates instead of building repos.
var wikiGitDate = func(projectDir, specPath string) string {
	out, err := exec.Command("git", "-C", projectDir, "log", "-1", "--format=%as", "--", specPath).Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(out))
}

func renderWikiHTML(projectDir string, caps []wikiCapability) []byte {
	name := html.EscapeString(filepath.Base(projectDir))
	total := 0
	maxCrit := 1
	for _, c := range caps {
		total += len(c.criteria)
		if len(c.criteria) > maxCrit {
			maxCrit = len(c.criteria)
		}
	}

	var b strings.Builder
	b.WriteString(wikiHTMLMarker + "\n")
	b.WriteString("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
	b.WriteString("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
	fmt.Fprintf(&b, "<title>Specs — %s</title>\n", name)
	b.WriteString(`<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,500;9..144,600&family=Public+Sans:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500&display=swap">
<style>` + wikiCSS + `</style>
</head>
<body>
<div id="progress"></div>
<main>
<section id="home">
`)
	fmt.Fprintf(&b, "<h1>%s</h1>\n", name)
	fmt.Fprintf(&b, "<p class=\"tag\">%d capabilities · %d anchored criteria · generated by <code>libretto wiki --html</code></p>\n",
		len(caps), total)
	// The board: health bar, recent rail, in-flight strip. Every arm renders
	// only when its data exists — absent is absent, never an error.
	earsN, unproven := 0, 0
	for _, c := range caps {
		for _, cr := range c.criteria {
			if isEARS(cr.text) {
				earsN++
			}
			if !proofResolves(projectDir, cr) {
				unproven++
			}
		}
	}
	if total > 0 {
		green := earsN * 100 / total
		fmt.Fprintf(&b, "<div class=\"health\"><div class=\"health-bar\"><i class=\"seg ok\" style=\"width:%d%%\"></i><i class=\"seg warn\" style=\"width:%d%%\"></i></div><span class=\"health-note\">%d%% EARS \u00b7 %d unproven</span></div>\n",
			green, 100-green, green, unproven)
	}
	recent := make([]wikiCapability, 0, len(caps))
	for _, c := range caps {
		if c.changed != "" {
			recent = append(recent, c)
		}
	}
	sort.SliceStable(recent, func(i, j int) bool { return recent[i].changed > recent[j].changed })
	if len(recent) > 3 {
		recent = recent[:3]
	}
	if len(recent) > 0 {
		b.WriteString("<div class=\"rail\">\n")
		for _, c := range recent {
			fmt.Fprintf(&b, "<a class=\"recent\" href=\"#%s\"><span class=\"card-name\">%s</span><span class=\"date\">%s</span><span class=\"subject\">%s</span></a>\n",
				html.EscapeString(c.name), html.EscapeString(c.name), html.EscapeString(c.changed), html.EscapeString(c.subject))
		}
		b.WriteString("</div>\n")
	}
	flights, queued := readInFlight(projectDir)
	if len(flights) > 0 {
		b.WriteString("<div class=\"inflight\"><span class=\"pulse\"></span><span class=\"inflight-label\">in flight</span>\n")
		for _, f := range flights {
			fmt.Fprintf(&b, "<span class=\"flight\">%s <b>%d/%d</b></span>\n", html.EscapeString(f.name), f.closed, f.closed+f.open)
		}
		if queued > 0 {
			fmt.Fprintf(&b, "<span class=\"queued\">%d queued</span>\n", queued)
		}
		b.WriteString("</div>\n")
	}
	b.WriteString("<input id=\"filter\" type=\"search\" placeholder=\"Filter capabilities and criteria…\" aria-label=\"Filter capabilities and criteria\">\n")
	b.WriteString("<div class=\"cards\">\n")
	for _, c := range caps {
		texts := make([]string, 0, len(c.criteria))
		for _, cr := range c.criteria {
			texts = append(texts, cr.text)
		}
		crit := strings.ToLower(strings.Join(texts, " "))
		health := "warn"
		if capHealthy(projectDir, c) {
			health = "ok"
		}
		fmt.Fprintf(&b, "<a class=\"card\" href=\"#%s\" data-crit=\"%s\" data-health=\"%s\">\n", html.EscapeString(c.name), html.EscapeString(crit), health)
		fmt.Fprintf(&b, "<span class=\"card-top\"><span class=\"card-name\">%s</span><span class=\"dot %s\"></span></span>\n", html.EscapeString(c.name), health)
		fmt.Fprintf(&b, "<span class=\"card-meta\"><span>%d criteria</span>", len(c.criteria))
		if c.changed != "" {
			fmt.Fprintf(&b, "<span class=\"date\">%s</span>", html.EscapeString(c.changed))
		}
		b.WriteString("</span>\n")
		fmt.Fprintf(&b, "<span class=\"bar\"><i style=\"width:%d%%\"></i></span>\n</a>\n", len(c.criteria)*100/maxCrit)
	}
	b.WriteString("</div>\n")
	if tracked := wikiGitTracked(projectDir); len(tracked) > 0 {
		var globs []string
		for _, c := range caps {
			globs = append(globs, strings.Fields(c.governs)...)
		}
		governed, orphan := governedSplit(tracked, globs)
		fmt.Fprintf(&b, "<p class=\"governed\">%d governed \u00b7 %d orphan \u2014 of %d tracked files</p>\n", governed, orphan, len(tracked))
	}
	b.WriteString("</section>\n")
	for _, c := range caps {
		fmt.Fprintf(&b, "<article class=\"cap\" id=\"%s\">\n<a class=\"back\" href=\"#home\">← home</a>\n<h2>%s</h2>\n",
			html.EscapeString(c.name), html.EscapeString(c.name))
		if c.changed != "" {
			fmt.Fprintf(&b, "<p class=\"changed\">last changed <span class=\"date\">%s</span></p>\n", html.EscapeString(c.changed))
		}
		if spark := renderSparkline(monthBuckets(wikiGitDates(projectDir, filepath.Join(specsDirOf(projectDir), c.name, "spec.md")))); spark != "" {
			fmt.Fprintf(&b, "<p class=\"activity\">%s</p>\n", spark)
		}
		if len(c.intro) > 0 {
			fmt.Fprintf(&b, "<p class=\"intro\">%s</p>\n", htmlInline(strings.Join(c.intro, " ")))
		}
		if c.governs != "" {
			fmt.Fprintf(&b, "<p class=\"governs\"><span class=\"lbl\">Governs</span><code>%s</code></p>\n",
				html.EscapeString(c.governs))
		}
		if len(c.decisions) > 0 {
			shown := c.decisions
			if len(shown) > 3 {
				shown = shown[:3]
			}
			fmt.Fprintf(&b, "<div class=\"decisions\"><p class=\"lbl\">Prior decisions · %d</p><ul>\n", len(c.decisions))
			for _, d := range shown {
				fmt.Fprintf(&b, "<li>%s</li>\n", htmlInline(d))
			}
			b.WriteString("</ul></div>\n")
		}
		if len(c.criteria) > 0 {
			b.WriteString("<ul class=\"crit\">\n")
			for _, crit := range c.criteria {
				chip := ""
				if crit.proofFile != "" {
					label := crit.proofFile
					if crit.proofTest != "" && strings.HasSuffix(crit.proofFile, ".go") {
						label += " · " + crit.proofTest
					}
					state := "warn"
					if isEARS(crit.text) && proofResolves(projectDir, crit) {
						state = "ok"
					}
					chip = fmt.Sprintf(" <span class=\"chip %s\">%s</span>", state, html.EscapeString(label))
				}
				fmt.Fprintf(&b, "<li>%s%s</li>\n", htmlInline(crit.text), chip)
			}
			b.WriteString("</ul>\n")
		} else {
			b.WriteString("<p class=\"none\">No anchored criteria yet — this capability migrates when a delta lands on it.</p>\n")
		}
		if rel := relatedTo(c, caps); len(rel) > 0 {
			b.WriteString("<p class=\"related\"><span class=\"lbl\">Related</span>")
			for _, r := range rel {
				fmt.Fprintf(&b, " <a href=\"#%s\">%s</a>", html.EscapeString(r), html.EscapeString(r))
			}
			b.WriteString("</p>\n")
		}
		b.WriteString("</article>\n")
	}
	b.WriteString("</main>\n<script>" + wikiJS + "</script>\n</body>\n</html>\n")
	return []byte(b.String())
}

