// wikiGitSubject: the subject of the last commit touching the spec — the "what
// changed" beside the rail's date. Same failure contract as wikiGitDate.
var wikiGitSubject = func(projectDir, specPath string) string {
	out, err := exec.Command("git", "-C", projectDir, "log", "-1", "--format=%s", "--", specPath).Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(out))
}

// wikiGitTracked: the files git tracks, for the governed-tree footer. nil on any
// failure, and the footer is simply absent.
var wikiGitTracked = func(projectDir string) []string {
	out, err := exec.Command("git", "-C", projectDir, "ls-files", "-z").Output()
	if err != nil || len(out) == 0 {
		return nil
	}
	parts := strings.Split(strings.TrimRight(string(out), "\x00"), "\x00")
	files := parts[:0]
	for _, p := range parts {
		if p != "" {
			files = append(files, p)
		}
	}
	return files
}

var wikiShallRe = regexp.MustCompile(`\bshall\b`)

// isEARS mirrors spec-drift's marker: `shall`, with emphasis and backticks
// stripped first so **shall** and `shall` still count.
func isEARS(text string) bool {
	return wikiShallRe.MatchString(strings.NewReplacer("*", "", "`", "").Replace(text))
}

// proofResolves mirrors the anchor: the cited file exists, and a Go test
// citation names a test the file declares. A non-Go second token is a command
// argument, not a test — file existence is the whole check there.
func proofResolves(projectDir string, cr wikiCriterion) bool {
	if cr.proofFile == "" {
		return false
	}
	path := filepath.Join(projectDir, cr.proofFile)
	if cr.proofTest != "" && strings.HasSuffix(cr.proofFile, ".go") {
		b, err := os.ReadFile(path)
		if err != nil {
			return false
		}
		return strings.Contains(string(b), "func "+cr.proofTest+"(")
	}
	_, err := os.Stat(path)
	return err == nil
}

func capHealthy(projectDir string, c wikiCapability) bool {
	for _, cr := range c.criteria {
		if !isEARS(cr.text) || !proofResolves(projectDir, cr) {
			return false
		}
	}
	return true
}

// governedSplit mirrors spec-drift's matches_any, which is a bash case pattern:
// `*` there crosses directory separators, so the translation is deliberate —
// `**` and `*` both become .* and `?` becomes one character. Diverging from the
// script here would be two authorities.
func governedSplit(tracked []string, globs []string) (governed, orphan int) {
	res := make([]*regexp.Regexp, 0, len(globs))
	for _, g := range globs {
		quoted := regexp.QuoteMeta(g)
		quoted = strings.ReplaceAll(quoted, `\*\*`, `.*`)
		quoted = strings.ReplaceAll(quoted, `\*`, `.*`)
		quoted = strings.ReplaceAll(quoted, `\?`, `.`)
		res = append(res, regexp.MustCompile("^"+quoted+"$"))
	}
	for _, f := range tracked {
		hit := false
		for _, re := range res {
			if re.MatchString(f) {
				hit = true
				break
			}
		}
		if hit {
			governed++
		} else {
			orphan++
		}
	}
	return governed, orphan
}

// wikiFlight is one open change for the in-flight strip.
type wikiFlight struct {
	name         string
	closed, open int
}

// readInFlight walks the changes directory with the loop's own box definition:
// tasks.md, falling back to the legacy plan.md. Zero open boxes is landed-shape
// and never shows; queued proposals are counted, never listed here.
func readInFlight(projectDir string) (flights []wikiFlight, queued int) {
	changes := filepath.Join(projectDir, ".agents", "changes")
	entries, err := os.ReadDir(changes)
	if err != nil {
		return nil, 0
	}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		dir := filepath.Join(changes, e.Name())
		if b, err := os.ReadFile(filepath.Join(dir, "proposal.md")); err == nil {
			for _, line := range strings.Split(string(b), "\n") {
				if strings.HasPrefix(line, "Queued:") {
					queued++
					break
				}
			}
		}
		list, err := os.ReadFile(filepath.Join(dir, "tasks.md"))
		if err != nil {
			list, err = os.ReadFile(filepath.Join(dir, "plan.md"))
		}
		if err != nil {
			continue
		}
		f := wikiFlight{name: e.Name()}
		for _, line := range strings.Split(string(list), "\n") {
			t := strings.TrimSpace(line)
			if strings.HasPrefix(t, "- [ ]") {
				f.open++
			} else if strings.HasPrefix(t, "- [x]") {
				f.closed++
			}
		}
		if f.open > 0 {
			flights = append(flights, f)
		}
	}
	return flights, queued
}

// wikiGitDates: every commit date touching the spec, newest first — the
// sparkline's raw material. Same failure contract as its siblings.
var wikiGitDates = func(projectDir, specPath string) []string {
	out, err := exec.Command("git", "-C", projectDir, "log", "--format=%as", "--", specPath).Output()
	if err != nil {
		return nil
	}
	var dates []string
	for _, l := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		if l != "" {
			dates = append(dates, l)
		}
	}
	return dates
}

// monthBuckets anchors at the newest date's month — never at the clock — and
// walks back eight months. A function of history alone, so bytes hold still.
func monthBuckets(dates []string) [8]int {
	var buckets [8]int
	if len(dates) == 0 {
		return buckets
	}
	anchor := dates[0][:7] // newest first
	ay, _ := strconv.Atoi(anchor[:4])
	am, _ := strconv.Atoi(anchor[5:7])
	idx := func(month string) int {
		y, _ := strconv.Atoi(month[:4])
		m, _ := strconv.Atoi(month[5:7])
		return (ay-y)*12 + (am - m) // 0 = anchor month
	}
	for _, d := range dates {
		if len(d) < 7 {
			continue
		}
		if i := idx(d[:7]); i >= 0 && i < 8 {
			buckets[7-i]++
		}
	}
	return buckets
}

// relatedTo: which other capabilities this spec's raw text names, on a
// case-insensitive word boundary — assumed rule, recorded in the spec.
func relatedTo(c wikiCapability, caps []wikiCapability) []string {
	var out []string
	for _, other := range caps {
		if other.name == c.name {
			continue
		}
		re := regexp.MustCompile(`(?i)\b` + regexp.QuoteMeta(other.name) + `\b`)
		if re.MatchString(c.raw) {
			out = append(out, other.name)
		}
	}
	return out
}

func renderSparkline(buckets [8]int) string {
	max := 1
	total := 0
	for _, n := range buckets {
		total += n
		if n > max {
			max = n
		}
	}
	if total == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString(`<svg class="spark" viewBox="0 0 78 20" aria-label="commit activity, last eight months">`)
	for i, n := range buckets {
		h := n * 18 / max
		if n > 0 && h == 0 {
			h = 1
		}
		fmt.Fprintf(&b, `<rect x="%d" y="%d" width="8" height="%d" rx="1.5"></rect>`, i*10, 20-h, h)
	}
	b.WriteString("</svg>")
	return b.String()
}

